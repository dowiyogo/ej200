#!/usr/bin/env python3
"""
results_macros.py  —  Generate LaTeX macros from phase_ab_optimal.csv.

Source: analysis/optim/phase_ab_optimal.csv  (END-only, GEN-3, scan_end_vikuiti)
Output: presentations/v6/results_macros.tex

Per material emits:
  Res<qty><mat>   where mat in {ejA=EJ-200, ejB=EJ-204, ejC=EJ-230}
"""

import csv
import math
from pathlib import Path

REPO   = Path(__file__).resolve().parents[3]
SRCCSV = REPO / "analysis/optim/phase_ab_optimal.csv"
OUTDIR = Path(__file__).resolve().parents[1]   # presentations/v6/
OUTTEX = OUTDIR / "results_macros.tex"

MAT_TAG = {"ej200": "ejA", "ej204": "ejB", "ej230": "ejC"}
MAT_LABEL = {"ej200": "EJ-200", "ej204": "EJ-204", "ej230": "EJ-230"}

rows_by_mat = {m: [] for m in MAT_TAG}
with open(SRCCSV) as f:
    for row in csv.DictReader(f):
        mat = row["scint"]
        rows_by_mat[mat].append({
            "x":         int(row["x"]),
            "m_opt":     int(row["m_opt"]),
            "sig_m_opt": float(row["sig_m_opt"]),
            "npe_L":     float(row["npe_L"]),
            "npe_R":     float(row["npe_R"]),
        })

def fmt_ps(v): return f"{v:.2f}\\,\\text{{ps}}"
def fmt_bare(v): return f"{v:.2f}"          # bare number, no units (for table cells with unit header)
def fmt_mm(v): return f"{int(v):+d}\\,\\text{{mm}}" if v != 0 else "0\\,\\text{{mm}}"
def fmt_pe(v): return f"{v:.0f}\\,\\text{{pe}}"
def fmt_int(v): return str(v)

lines = ["% results_macros.tex — AUTO-GENERATED by scripts/results_macros.py, do not edit",
         f"% Source: {SRCCSV.relative_to(REPO)}",
         ""]

for mat, tag in MAT_TAG.items():
    data = sorted(rows_by_mat[mat], key=lambda r: r["x"])
    sigs = [r["sig_m_opt"] for r in data]

    x0  = next(r for r in data if r["x"] == 0)
    sig_x0  = x0["sig_m_opt"]
    mopt_x0 = x0["m_opt"]
    npe_x0  = (x0["npe_L"] + x0["npe_R"]) / 2.0

    sig_mean = sum(sigs) / len(sigs)

    min_sig = min(sigs)
    x_min   = next(r["x"] for r in data if r["sig_m_opt"] == min_sig)

    label = MAT_LABEL[mat]
    lines.append(f"% {label}")
    lines.append(f"\\newcommand{{\\RessigmaxzERO{tag}}}{{{fmt_ps(sig_x0)}}}  % {label} sigma_m*(x=0) with units")
    lines.append(f"\\newcommand{{\\RessigmabxzERO{tag}}}{{{fmt_bare(sig_x0)}}}  % {label} sigma_m*(x=0) bare (for table)")
    lines.append(f"\\newcommand{{\\ResmoptxzERO{tag}}}{{{fmt_int(mopt_x0)}}}  % {label} m* at x=0")
    lines.append(f"\\newcommand{{\\RessigmamEAN{tag}}}{{{fmt_ps(sig_mean)}}}  % {label} bar-mean sigma_m* with units")
    lines.append(f"\\newcommand{{\\RessigmabmEAN{tag}}}{{{fmt_bare(sig_mean)}}}  % {label} bar-mean sigma_m* bare (for table)")
    lines.append(f"\\newcommand{{\\RessigmaMIN{tag}}}{{{fmt_ps(min_sig)}}}  % {label} min sigma_m* on bar")
    lines.append(f"\\newcommand{{\\ResxMIN{tag}}}{{{fmt_mm(x_min)}}}  % {label} x at min sigma")
    lines.append(f"\\newcommand{{\\ResNpexzERO{tag}}}{{{fmt_pe(npe_x0)}}}  % {label} mean N_pe/end at x=0")
    lines.append("")

with open(OUTTEX, "w") as f:
    f.write("\n".join(lines))

print(f"Wrote {OUTTEX}  ({sum(1 for l in lines if l.startswith(chr(92)))} macros)")
for mat, tag in MAT_TAG.items():
    data = sorted(rows_by_mat[mat], key=lambda r: r["x"])
    x0 = next(r for r in data if r["x"] == 0)
    sigs = [r["sig_m_opt"] for r in data]
    min_s = min(sigs)
    x_m   = next(r["x"] for r in data if r["sig_m_opt"] == min_s)
    print(f"  {MAT_LABEL[mat]:8s}  σ(x=0)={x0['sig_m_opt']:.2f}ps  mean={sum(sigs)/len(sigs):.2f}ps  "
          f"min={min_s:.2f}ps@x={x_m:+d}")
