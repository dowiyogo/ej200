def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pres-dir", default=str(PRES_DIR), type=pathlib.Path,
                    help="Directory with deck_values.json, figures/, tables/")
    ap.add_argument("--skip-compile", action="store_true",
                    help="Write main.tex but skip latexmk")
    args = ap.parse_args()

    pres_dir = args.pres_dir.resolve()
    v   = _load_values(pres_dir)
    tex = build_tex(pres_dir, v)

    tex_path = pres_dir / "main.tex"
    tex_path.write_text(tex)
    print(f"Written: {tex_path}")

    # Unresolved placeholders check
    import re
    remaining = re.findall(r"@[A-Z0-9_]+@", tex)
    if remaining:
        print(f"WARNING: {len(remaining)} unresolved placeholders: {set(remaining)}")

    if args.skip_compile:
        print("Skipping LaTeX compilation (--skip-compile).")
        return

    pdf_path = pres_dir / "main.pdf"
    env = dict(os.environ)

    latexmk = shutil.which("latexmk")
    if latexmk:
        cmd = [latexmk, "-pdf", "-interaction=nonstopmode",
               "-halt-on-error",
               f"-output-directory={pres_dir}", str(tex_path)]
        r = subprocess.run(cmd, cwd=str(pres_dir), capture_output=True, text=True, env=env)
        if r.returncode != 0:
            print("latexmk FAILED. Last 3000 chars of stderr:")
            print(r.stderr[-3000:])
            # also show log
            log_path = pres_dir / "main.log"
            if log_path.exists():
                lines = log_path.read_text().splitlines()
                err_lines = [l for l in lines if "Error" in l or "error" in l or "!" in l]
                print("Log errors:")
                for l in err_lines[-20:]:
                    print(" ", l)
        success = r.returncode == 0
    else:
        r = None
        for _ in range(2):
            r = subprocess.run(
                ["pdflatex", "-interaction=nonstopmode",
                 "-output-directory", str(pres_dir), str(tex_path)],
                cwd=str(pres_dir), capture_output=True, text=True, env=env,
            )
        success = (r is not None and r.returncode == 0)
        if not success and r:
            print("pdflatex FAILED. stderr:", r.stderr[-2000:])

    if success and pdf_path.exists():
        try:
            pg = subprocess.run(["pdfinfo", str(pdf_path)],
                                capture_output=True, text=True)
            pages = next(
                (ln.split(":")[1].strip()
                 for ln in pg.stdout.splitlines()
                 if ln.startswith("Pages:")), "?")
        except Exception:
            pages = "?"
        print(f"PDF compiled: {pdf_path}  ({pages} pages)")
    else:
        print("WARNING: PDF may have failed. Check main.log.")


if __name__ == "__main__":
    main()
