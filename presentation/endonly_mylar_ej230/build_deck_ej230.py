def build_tex(pres_dir: pathlib.Path, v: dict) -> str:
    sigma_at = v.get("sigma_t_at_key_positions", {})

    def sg(xkey: str) -> str:
        d = sigma_at.get(str(xkey), {})
        # addendum: use sigma_eq (= sigma(tL-tR)/sqrt(2)); stored as sigma_single_ps
        s = d.get("sigma_eq_ps") or d.get("sigma_single_ps")
        e = d.get("sigma_eq_err_ps") or d.get("sigma_single_err_ps")
        if s is None:
            return r"\texttt{n/a}"
        return f"{float(s):.0f}\\pm{float(e):.0f}"

    att_l = v.get("att_left", {})
    att_r = v.get("att_right", {})

    def _pm(key_val, key_err, d, decimals=1):
        val = d.get(key_val)
        err = d.get(key_err)
        return _pmfmt(val, err, decimals)

    et    = v.get("endtop", {})
    et_av = et.get("available", False)
    et_fl = et.get("fit_left", {})
    lam_tail_et_str = (_pm("tail_lam_cm", "tail_lam_err", et_fl, 1)
                       if et_av else r"\texttt{n/a}")

    rs = v.get("att_tail_range_sensitivity", {})
    def _rs_lam(dmin_key, side):
        d2 = rs.get(f"dmin_{dmin_key}cm", {}).get(side)
        if not d2:
            return r"\texttt{n/a}"
        return _pmfmt(d2.get("lam_cm"), d2.get("lam_err"), 1)
    def _rs_chi(dmin_key, side):
        d2 = rs.get(f"dmin_{dmin_key}cm", {}).get(side)
        if not d2:
            return r"\texttt{n/a}"
        val = d2.get("chi2ndf")
        return _fmt(val, 0) if val else r"\texttt{n/a}"

    # Bootstrap: use C++ OpenMP results (authoritative)
    boot_cpp = att_l.get("bootstrap_cpp", {})
    def _boot(key, stat):
        d2 = boot_cpp.get(key, {})
        if not d2:
            return r"\texttt{n/a}"
        val = d2.get(stat)
        return f"{float(val):.1f}" if val is not None else r"\texttt{n/a}"

    pct_sb   = v.get("photon_budget_pct_surface_bulk")
    pct_esc  = v.get("photon_budget_pct_escaped")
    pct_sipm = v.get("photon_budget_pct_sipm")
