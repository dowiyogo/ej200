def build_tex(out_dir: pathlib.Path, v: dict) -> str:
    tab_map  = v.get("tables", {})
    sigma_at = v.get("sigma_t_at_key_positions", {})

    def sg(xkey: str) -> str:
        d = sigma_at.get(str(xkey), {})
        s = d.get("sigma_single_ps")
        e = d.get("sigma_single_err_ps")
        if s is None:
            return r"\texttt{n/a}"
        return f"{float(s):.0f}\\pm{float(e):.0f}"

    # Attenuation fit values
    att_l = v.get("att_left", {})
    att_r = v.get("att_right", {})

    def _pm(key_val, key_err, d, decimals=1):
        val = d.get(key_val)
        err = d.get(key_err)
        return _pmfmt(val, err, decimals)

    # EndTop
    et    = v.get("endtop", {})
    et_av = et.get("available", False)
    et_fl = et.get("fit_left", {})
    lam_tail_et_str = (_pm("tail_lam_cm", "tail_lam_err", et_fl)
                       if et_av else r"\texttt{n/a}")
    npe_tail_et_str = (_fmt(et.get("npe_left_at_x0"), 1)
                       if et_av else r"\texttt{n/a}")

    # Range sensitivity
    rs = v.get("att_tail_range_sensitivity", {})
    def _rs_lam(dmin_key, side):
        d = rs.get(f"dmin_{dmin_key}cm", {}).get(side)
        if not d:
            return r"\texttt{n/a}"
        return _pmfmt(d.get("lam_cm"), d.get("lam_err"))
    def _rs_chi(dmin_key, side):
        d = rs.get(f"dmin_{dmin_key}cm", {}).get(side)
        if not d:
            return r"\texttt{n/a}"
        v2 = d.get("chi2ndf")
        return _fmt(v2, 0) if v2 else r"\texttt{n/a}"

    # Bootstrap (left side)
    boot_l = att_l.get("bootstrap") or {}
    def _boot_val(key, stat):
        d2 = boot_l.get(key)
        if not d2:
            return r"\texttt{n/a}"
        val = d2.get(stat)
        return f"{float(val):.1f}" if val is not None else r"\texttt{n/a}"
    def _boot_fail():
        f = boot_l.get("M2_failure_fraction")
        if f is None:
            return r"\texttt{n/a}"
        return f"{float(f)*100:.0f}"

