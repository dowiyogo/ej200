def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir",
                    default="/home/reriosto/SHiP/t0minidaq/endonly_mylar_20260614",
                    type=pathlib.Path)
    ap.add_argument("--out-dir", default=HERE, type=pathlib.Path)
    ap.add_argument("--skip-analysis", action="store_true")
    ap.add_argument("--no-compile",    action="store_true")
    args = ap.parse_args()

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    if not args.skip_analysis:
        _run_analysis(args.data_dir, out_dir)

    v   = _load_values(out_dir)
    tex = build_tex(out_dir, v)

    tex_path = out_dir / "main.tex"
    tex_path.write_text(tex)
    print(f"Written: {tex_path}")

    if args.no_compile:
        print("Skipping LaTeX compilation (--no-compile).")
        return

    pdf_path = out_dir / "main.pdf"
    env = dict(os.environ)

    latexmk = shutil.which("latexmk")
    if latexmk:
        cmd = [latexmk, "-pdf", "-interaction=nonstopmode",
               "-halt-on-error",
               f"-output-directory={out_dir}", str(tex_path)]
        r = subprocess.run(cmd, cwd=str(out_dir), capture_output=True, text=True, env=env)
        if r.returncode != 0:
            print("latexmk stderr:", r.stderr[-4000:])
        success = r.returncode == 0
    else:
        r = None
        for _ in range(2):
            r = subprocess.run(
                ["pdflatex", "-interaction=nonstopmode",
                 "-output-directory", str(out_dir), str(tex_path)],
                cwd=str(out_dir), capture_output=True, text=True, env=env,
            )
        success = (r is not None and r.returncode == 0)
        if not success and r:
            print("pdflatex stderr:", r.stderr[-2000:])

    if success and pdf_path.exists():
        try:
            pg_info = subprocess.run(["pdfinfo", str(pdf_path)],
                                     capture_output=True, text=True)
            pages = next(
                (ln.split(":")[1].strip()
                 for ln in pg_info.stdout.splitlines()
                 if ln.startswith("Pages:")), "?"
            )
        except Exception:
            pages = "?"
        print(f"PDF compiled successfully: {pdf_path.name}  ({pages} pages)")
    else:
        print("WARNING: PDF compilation may have failed. Check main.log for details.")


if __name__ == "__main__":
    main()
