def _run_analysis(data_dir: pathlib.Path, out_dir: pathlib.Path) -> None:
    script = HERE / "analysis_endonly_mylar.py"
    if not script.exists():
        sys.exit(f"ERROR: analysis_endonly_mylar.py not found at {script}")
    print("Running analysis...")
    subprocess.run([sys.executable, str(script),
                    "--data-dir", str(data_dir),
                    "--out-dir", str(out_dir)], check=True)


def _load_values(out_dir: pathlib.Path) -> dict:
    p = out_dir / "deck_values.json"
    if not p.exists():
        sys.exit("ERROR: deck_values.json not found. Run without --skip-analysis first.")
    with open(p) as f:
        return json.load(f)


def _fmt(v, decimals: int = 1, unit: str = "") -> str:
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return r"\texttt{n/a}"
    s = f"{float(v):.{decimals}f}"
    return s + (r"\," + unit if unit else "")


def _fmt_int(v) -> str:
    if v is None:
        return r"\texttt{n/a}"
    return f"{int(v):,}"


def _sub(template: str, subs: dict[str, str]) -> str:
    for key, val in subs.items():
        template = template.replace(f"@{key}@", val)
    return template


def _read_tex(out_dir: pathlib.Path, tab_key: str, tab_map: dict) -> str:
    rel = tab_map.get(tab_key, f"tables/{tab_key}")
    p = out_dir / (rel + ".tex")
    return p.read_text() if p.exists() else f"% {tab_key} not found\n"


def _pmfmt(val, err, decimals: int = 1) -> str:
    """Format value±error as LaTeX math string (no outer $)."""
    if val is None or err is None:
        return r"\texttt{n/a}"
    if not (math.isfinite(float(val)) and math.isfinite(float(err))):
        return r"\texttt{n/a}"
    return f"{float(val):.{decimals}f}\\pm{float(err):.{decimals}f}"


def _na_or(v, fmt=".1f") -> str:
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return r"\texttt{n/a}"
    return f"{float(v):{fmt}}"


